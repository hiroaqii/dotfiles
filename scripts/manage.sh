#!/usr/bin/env bash
set -euo pipefail
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
action=${1:?Specify setup:plan, setup, status, update, or upgrade}
profile=${MISE_ENV:-}
case ",$profile," in *,macos,*) platform=macos ;; *,omarchy,*) platform=omarchy ;; *) echo 'Select -E macos,work or -E omarchy,personal.' >&2; exit 1 ;; esac
case ",$profile," in *,work,*) purpose=work ;; *,personal,*) purpose=personal ;; *) echo 'Select work or personal.' >&2; exit 1 ;; esac
if [[ ",$profile," == *,macos,* && ",$profile," == *,omarchy,* ]] || [[ ",$profile," == *,work,* && ",$profile," == *,personal,* ]]; then
  echo 'Select exactly one OS and one purpose.' >&2; exit 1
fi
case "$platform:$(uname -s)" in macos:Darwin|omarchy:Linux) ;; *) echo 'Selected OS does not match this machine.' >&2; exit 1 ;; esac
m() { mise -C "$root/mise" -E "$platform,$purpose" "$@"; }
# The system CLI tools deliberately remain owned by Omarchy.
check_system() {
  local name missing=0
  if [[ $platform == omarchy ]]; then
    for name in fzf herdr jq lazygit rg starship zoxide; do
      if ! command -v "$name" >/dev/null 2>&1; then
        echo "Missing Omarchy tool: $name" >&2; missing=1
      fi
    done
  fi
  return "$missing"
}
# Generate tool declarations and exclusions for use outside the checkout. Keep tasks and
# deployment rules local to the repository. Profiles override earlier values.
write_global_tools() {
  local dir="${XDG_CONFIG_HOME:-$HOME/.config}/mise/conf.d" tmp
  mkdir -p "$dir"
  tmp=$(mktemp)
  awk '
    /^disable_tools *=/ { disabled=$0 }
    /^\[tools\]$/ { tools=1; next }
    /^\[/ { tools=0 }
    tools && /^[^#[:space:]][^=]*=/ { key=$0; sub(/=.*/, "", key); gsub(/[[:space:]]/, "", key); entries[key]=$0 }
    END { print "# Generated by dotfiles setup. Edit the source in the repository."; print "[tools]"; for (key in entries) print entries[key]; if (disabled != "") { print "\n[settings]"; print disabled } }
  ' "$root/mise/mise.toml" "$root/mise/mise.$platform.toml" "$root/mise/mise.$purpose.toml" > "$tmp"
  if [[ -e "$dir/90-dotfiles.toml" ]] && ! grep -q '^# Generated by dotfiles setup\.' "$dir/90-dotfiles.toml"; then
    rm -f "$tmp"; echo 'Unmanaged 90-dotfiles.toml exists; refusing to overwrite.' >&2; return 1
  fi
  mv "$tmp" "$dir/90-dotfiles.toml"
}
activate_shell() {
  local rc line
  if [[ $platform == macos ]]; then
    rc="$HOME/.zshrc"
    line='source "$HOME/.config/zsh/dotfiles.zsh"'
  else
    rc="$HOME/.bashrc"
    line='eval "$(mise activate bash)"'
  fi
  if ! grep -qF '# BEGIN mise-dotfiles' "$rc" 2>/dev/null; then
    [[ ! -f "$rc" ]] || cp -p "$rc" "$rc.bak.$(date +%Y%m%d-%H%M%S)"
    printf '\n# BEGIN mise-dotfiles\n%s\n# END mise-dotfiles\n' "$line" >> "$rc"
  fi
}
ensure_system() {
  [[ $platform == omarchy ]] || return 0
  local spec name package
  for spec in fzf:fzf herdr:herdr jq:jq lazygit:lazygit rg:ripgrep starship:starship zoxide:zoxide; do
    name=${spec%%:*}; package=${spec#*:}
    if ! command -v "$name" >/dev/null 2>&1; then
      command -v omarchy >/dev/null 2>&1 || { echo 'Omarchy CLI is required for missing system packages.' >&2; return 1; }
      omarchy pkg add "$package"
    fi
  done
}
apply() {
  # Detect configuration collisions before downloading anything. No --force.
  m dotfiles apply --dry-run
  ensure_system
  check_system
  m install
  m bootstrap repos apply
  m dotfiles apply
  if [[ $platform == omarchy ]]; then
    bash "$root/scripts/configure-hypr-mouse.sh"
    bash "$root/scripts/japanese-input.sh" apply
  fi
  if [[ $platform == macos ]]; then
    m exec -- zsh -c 'source "$HOME/.local/share/antidote/antidote.zsh"; antidote bundle < "${XDG_CONFIG_HOME:-$HOME/.config}/zsh/completions.txt" >/dev/null; antidote bundle < "${XDG_CONFIG_HOME:-$HOME/.config}/zsh/plugins.txt" >/dev/null'
  fi
  write_global_tools
  activate_shell
  echo 'Setup complete. Open a new shell. Existing shell settings remain in place.'
}
case "$action" in
  setup:plan)
    check_system || true
    if [[ $platform == omarchy ]]; then bash "$root/scripts/japanese-input.sh" plan; fi
    m ls --current
    m bootstrap repos apply --dry-run
    m dotfiles apply --dry-run
    if [[ $platform == omarchy ]]; then echo 'Setup adds a managed mouse configuration include to ~/.config/hypr/hyprland.lua (with backup).'; fi
    echo 'Setup also writes ~/.config/mise/conf.d/90-dotfiles.toml and adds a managed shell activation block.'
    ;;
  status)
    check_system || true
    if [[ $platform == omarchy ]]; then bash "$root/scripts/japanese-input.sh" plan; fi
    m ls --current
    m bootstrap repos status
    m dotfiles status
    ;;
  setup) apply ;;
  update)
    if [[ -n $(git -C "$root" status --porcelain) ]]; then
      echo 'Checkout has local changes; commit or stash them before update.' >&2; exit 1
    fi
    git -C "$root" pull --ff-only
    # Re-exec so the checked-out script, tasks, and declarations are current.
    exec mise -C "$root/mise" -E "$platform,$purpose" run setup
    ;;
  upgrade)
    check_system
    m upgrade
    m bootstrap repos update
    if [[ $platform == macos ]]; then
      m exec -- zsh -c 'source "$HOME/.local/share/antidote/antidote.zsh"; antidote update'
    fi
    write_global_tools
    echo 'OS-managed packages and mise itself are not upgraded by this task.'
    ;;
  *) echo "Unknown action: $action" >&2; exit 1 ;;
esac
